#!/usr/bin/env python
"""Summarize VLIN Vision/VLM/Expert sparsity and audited compute.

Inputs (generated by main.py sparsity export):
  sparsity/module_sparsity.csv
  sparsity/weight_sparsity_static.csv
  sparsity/quantization_manifest.csv
  sparsity/workload.csv

Outputs (under the task output directory):
  sparsity_compute_summary.csv   -- component-level runtime/static sparsity
  sparsity_by_operator.csv       -- secondary operator/role breakdown
  compute_summary.csv            -- per-sample_actions dense MAC/FLOP accounting

Primary sparsity uses *native* runtime counters only.  For PoT-FP8 + outlier
protection, reported counters include zeros manufactured by the normal path at
protected FP-sidepath positions and would overstate sparsity.

Compute accounting intentionally separates:
  1) dynamic quantized major-ops from workload.csv (Vision Linear + VLM/Expert
     Linear/MatMul), normalized to one sample_actions() generation;
  2) raw Vision SDPA QK/PV and raw connector projection from the V0-validated
     architecture formulas.

Non-GEMM ops (patch embed, LayerNorm, softmax, GELU, pixel-shuffle bookkeeping)
are not included in the audited-major-op total.  This is FLOP/MAC accounting,
NOT measured latency or speedup.
"""

from __future__ import annotations

import argparse
import csv
import math
import os
import statistics
import sys
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve()
REPO_ROOT = HERE.parents[5]
EXP = "2026-09-15_phaseI_vision-quantization"
TASK = "vision-sparsity-compute"
DEFAULT_OUT = (
    REPO_ROOT
    / "outputs"
    / EXP
    / "tasks"
    / TASK
    / "vsc_vlin_fp8_task0_1ep"
)

# V0-validated Vision architecture.
VISION_LAYERS = 12
VISION_TOKENS = 1024
VISION_HIDDEN = 768
VISION_INTERMEDIATE = 3072
VISION_HEADS = 12
VISION_HEAD_DIM = 64
CAMERAS = 2

# Connector after 4x pixel shuffle: 1024 -> 64 tokens, 16*768=12288 -> 960.
CONNECTOR_TOKENS = 64
CONNECTOR_IN = 12288
CONNECTOR_OUT = 960

EXPECTED = {
    "manifest_total": 360,
    "vision_linear": 72,
    "vlm_linear": 112,
    "expert_linear": 112,
    "vlm_matmul": 32,
    "expert_matmul": 32,
    "static_weight_rows": 296,
}


def read_csv(path: Path):
    if not path.is_file():
        raise FileNotFoundError(path)
    with path.open(newline="") as f:
        return list(csv.DictReader(f))


def f(row, key):
    try:
        return float(row.get(key, 0) or 0)
    except (TypeError, ValueError):
        return 0.0


def i(row, key):
    try:
        return int(float(row.get(key, 0) or 0))
    except (TypeError, ValueError):
        return 0


def ratio(num, den):
    return num / den if den else 0.0


def component_of(module_id: str) -> str:
    return (module_id or "unknown").split(".")[0]


def stage_label(component: str, phase: str) -> str:
    if component == "vision":
        return "Vision prefill"
    if component == "vlm":
        return "VLM prefill"
    if component == "expert":
        return "Expert denoise"
    return f"{component}:{phase or 'unknown'}"


def aggregate_sparsity(module_rows, weight_rows):
    rt = defaultdict(lambda: {"ze": 0, "te": 0, "zb": 0, "tb": 0, "rows": 0})
    rt_op = defaultdict(lambda: {"ze": 0, "te": 0, "zb": 0, "tb": 0})
    wt = defaultdict(lambda: {"ze": 0, "te": 0, "zb": 0, "tb": 0, "rows": 0})
    wt_op = defaultdict(lambda: {"ze": 0, "te": 0, "zb": 0, "tb": 0})

    for r in module_rows:
        comp = (r.get("component") or component_of(r.get("module_id", ""))).strip()
        if comp not in {"vision", "vlm", "expert"}:
            continue
        phase = (r.get("phase") or "").strip()
        op = (r.get("operator") or "?").strip()
        role = (r.get("tensor_role") or "?").strip()
        ze = i(r, "zero_elements_native")
        te = i(r, "total_elements_native")
        zb = i(r, "sparse_bits_native")
        tb = i(r, "total_bits_native")
        if min(ze, te, zb, tb) < 0:
            raise RuntimeError(f"negative native counter in {r.get('module_id')}")
        key = (comp, phase)
        rt[key]["ze"] += ze
        rt[key]["te"] += te
        rt[key]["zb"] += zb
        rt[key]["tb"] += tb
        rt[key]["rows"] += 1
        k2 = (comp, phase, op, role)
        rt_op[k2]["ze"] += ze
        rt_op[k2]["te"] += te
        rt_op[k2]["zb"] += zb
        rt_op[k2]["tb"] += tb

    for r in weight_rows:
        comp = (r.get("component") or component_of(r.get("module_id", ""))).strip()
        if comp not in {"vision", "vlm", "expert"}:
            continue
        op = (r.get("operator") or "?").strip()
        ze = i(r, "zero_elements")
        te = i(r, "total_elements")
        zb = i(r, "sparse_bits")
        tb = i(r, "total_bits")
        if min(ze, te, zb, tb) < 0:
            raise RuntimeError(f"negative weight counter in {r.get('module_id')}")
        wt[comp]["ze"] += ze
        wt[comp]["te"] += te
        wt[comp]["zb"] += zb
        wt[comp]["tb"] += tb
        wt[comp]["rows"] += 1
        k2 = (comp, op)
        wt_op[k2]["ze"] += ze
        wt_op[k2]["te"] += te
        wt_op[k2]["zb"] += zb
        wt_op[k2]["tb"] += tb

    summary = []
    for comp in ("vision", "vlm", "expert"):
        rt_entries = [v for (c, _), v in rt.items() if c == comp]
        a = {"ze": 0, "te": 0, "zb": 0, "tb": 0, "rows": 0}
        for x in rt_entries:
            for k in a:
                a[k] += x[k]
        w = wt[comp]
        phases = sorted({p for (c, p) in rt if c == comp})
        summary.append({
            "component": comp,
            "stage": "Vision prefill" if comp == "vision" else ("VLM prefill" if comp == "vlm" else "Expert denoise"),
            "phases": ";".join(phases),
            "runtime_rows": a["rows"],
            "runtime_total_elements_native": a["te"],
            "runtime_zero_elements_native": a["ze"],
            "runtime_element_sparsity_native": ratio(a["ze"], a["te"]),
            "runtime_total_bits_native": a["tb"],
            "runtime_sparse_bits_native": a["zb"],
            "runtime_bit_sparsity_native": ratio(a["zb"], a["tb"]),
            "weight_rows": w["rows"],
            "weight_total_elements": w["te"],
            "weight_zero_elements": w["ze"],
            "weight_element_sparsity": ratio(w["ze"], w["te"]),
            "weight_total_bits": w["tb"],
            "weight_sparse_bits": w["zb"],
            "weight_bit_sparsity": ratio(w["zb"], w["tb"]),
        })

    # Pooled quantized scope: sum numerators/denominators, never average ratios.
    pooled = {}
    for prefix, keys in {
        "runtime": ("runtime_zero_elements_native", "runtime_total_elements_native",
                    "runtime_sparse_bits_native", "runtime_total_bits_native"),
        "weight": ("weight_zero_elements", "weight_total_elements",
                   "weight_sparse_bits", "weight_total_bits"),
    }.items():
        pooled[prefix] = [sum(int(r[k]) for r in summary) for k in keys]
    summary.append({
        "component": "all_quantized",
        "stage": "Vision + VLM + Expert",
        "phases": "prefill;denoise",
        "runtime_rows": sum(int(r["runtime_rows"]) for r in summary),
        "runtime_total_elements_native": pooled["runtime"][1],
        "runtime_zero_elements_native": pooled["runtime"][0],
        "runtime_element_sparsity_native": ratio(pooled["runtime"][0], pooled["runtime"][1]),
        "runtime_total_bits_native": pooled["runtime"][3],
        "runtime_sparse_bits_native": pooled["runtime"][2],
        "runtime_bit_sparsity_native": ratio(pooled["runtime"][2], pooled["runtime"][3]),
        "weight_rows": sum(int(r["weight_rows"]) for r in summary),
        "weight_total_elements": pooled["weight"][1],
        "weight_zero_elements": pooled["weight"][0],
        "weight_element_sparsity": ratio(pooled["weight"][0], pooled["weight"][1]),
        "weight_total_bits": pooled["weight"][3],
        "weight_sparse_bits": pooled["weight"][2],
        "weight_bit_sparsity": ratio(pooled["weight"][2], pooled["weight"][3]),
    })

    operator_rows = []
    for (comp, phase, op, role), a in sorted(rt_op.items()):
        operator_rows.append({
            "kind": "runtime",
            "component": comp,
            "stage": stage_label(comp, phase),
            "phase": phase,
            "operator": op,
            "tensor_role": role,
            "total_elements": a["te"],
            "zero_elements": a["ze"],
            "element_sparsity": ratio(a["ze"], a["te"]),
            "total_bits": a["tb"],
            "sparse_bits": a["zb"],
            "bit_sparsity": ratio(a["zb"], a["tb"]),
        })
    for (comp, op), a in sorted(wt_op.items()):
        operator_rows.append({
            "kind": "weight_static",
            "component": comp,
            "stage": "static",
            "phase": "",
            "operator": op,
            "tensor_role": "weight",
            "total_elements": a["te"],
            "zero_elements": a["ze"],
            "element_sparsity": ratio(a["ze"], a["te"]),
            "total_bits": a["tb"],
            "sparse_bits": a["zb"],
            "bit_sparsity": ratio(a["zb"], a["tb"]),
        })
    return summary, operator_rows


def infer_generations(workload_rows):
    # Every Vision Linear executes once per camera.  With two cameras, its
    # activation-role call count should be 2 * sample_actions generations.
    per_mid = {}
    for r in workload_rows:
        mid = (r.get("module_id") or "").strip()
        if not mid.startswith("vision."):
            continue
        if (r.get("op_type") or "").strip() != "linear":
            continue
        if (r.get("tensor_role") or "").strip() != "activation":
            continue
        per_mid[mid] = i(r, "calls")
    if len(per_mid) != EXPECTED["vision_linear"]:
        raise RuntimeError(
            f"Vision activation workload sites={len(per_mid)}, expected 72"
        )
    vals = [v / CAMERAS for v in per_mid.values()]
    med = statistics.median(vals)
    if med <= 0 or abs(med - round(med)) > 1e-9:
        raise RuntimeError(f"invalid inferred sample_actions count: {med}")
    n_gen = int(round(med))
    if any(abs(v - n_gen) > 1e-9 for v in vals):
        raise RuntimeError(
            "Vision Linear call counts are inconsistent across sites: "
            f"{sorted(set(per_mid.values()))}"
        )
    return n_gen


def aggregate_compute(workload_rows):
    n_gen = infer_generations(workload_rows)
    totals = defaultdict(float)
    seen = set()

    for r in workload_rows:
        op_type = (r.get("op_type") or "").strip()
        role = (r.get("tensor_role") or "").strip()
        # Workload exporter emits one MAC estimate per tensor role.  Count the
        # physical op exactly once: activation for Linear, A for MatMul.
        if (op_type == "linear" and role != "activation") or (
            op_type == "matmul" and role != "A"
        ):
            continue
        mid = (r.get("module_id") or "").strip()
        phase = (r.get("phase") or "").strip()
        flow = (r.get("flow_step") or "").strip()
        key = (mid, phase, flow)
        if key in seen:
            continue
        seen.add(key)
        macs_per_call = f(r, "MACs")
        calls = i(r, "calls")
        totals[component_of(mid)] += macs_per_call * calls

    per_gen = {k: v / n_gen for k, v in totals.items()}

    # Raw Vision SDPA QK/PV, per sample_actions and across both cameras.
    qk_macs = (
        CAMERAS
        * VISION_LAYERS
        * VISION_HEADS
        * VISION_TOKENS
        * VISION_TOKENS
        * VISION_HEAD_DIM
    )
    pv_macs = qk_macs
    connector_macs = CAMERAS * CONNECTOR_TOKENS * CONNECTOR_IN * CONNECTOR_OUT

    rows = []
    def add(component, block, quantized, macs, note):
        rows.append({
            "component": component,
            "block": block,
            "quantized": "yes" if quantized else "no",
            "GMAC_per_sample_actions": macs / 1e9,
            "GFLOPs_per_sample_actions": 2.0 * macs / 1e9,
            "note": note,
        })

    add("vision", "Vision 72 Linear", True, per_gen.get("vision", 0.0),
        "runtime-derived from workload.csv; q/k/v/out + fc1/fc2")
    add("vision", "Vision SDPA QK", False, qk_macs,
        "V0 architecture formula; raw SDPA")
    add("vision", "Vision SDPA PV", False, pv_macs,
        "V0 architecture formula; raw SDPA")
    add("connector", "Connector projection", False, connector_macs,
        "64x12288 -> 960 per camera; raw")
    add("vlm", "VLM quantized major ops", True, per_gen.get("vlm", 0.0),
        "runtime-derived Linear + QK/PV")
    add("expert", "Expert quantized major ops (10 denoise)", True,
        per_gen.get("expert", 0.0),
        "runtime-derived across flow_step 0..9")

    total_macs = sum(float(r["GMAC_per_sample_actions"]) * 1e9 for r in rows)
    quant_macs = sum(
        float(r["GMAC_per_sample_actions"]) * 1e9
        for r in rows if r["quantized"] == "yes"
    )
    for r in rows:
        r["share_of_audited_major_ops"] = (
            (float(r["GMAC_per_sample_actions"]) * 1e9 / total_macs)
            if total_macs else 0.0
        )
    rows.append({
        "component": "TOTAL",
        "block": "audited major ops",
        "quantized": f"{quant_macs / total_macs:.6f}" if total_macs else "0",
        "GMAC_per_sample_actions": total_macs / 1e9,
        "GFLOPs_per_sample_actions": 2.0 * total_macs / 1e9,
        "share_of_audited_major_ops": 1.0,
        "note": (
            "quantized field is quantized-FLOP coverage; excludes patch embed/"
            "LayerNorm/softmax/GELU/pixel-shuffle bookkeeping"
        ),
    })
    return n_gen, rows, (quant_macs / total_macs if total_macs else 0.0)


def check_manifest(manifest_rows, weight_rows, module_rows, compute_rows, n_gen):
    errs = []
    if len(manifest_rows) != EXPECTED["manifest_total"]:
        errs.append(
            f"manifest rows={len(manifest_rows)} expected={EXPECTED['manifest_total']}"
        )

    counts = defaultdict(int)
    for r in manifest_rows:
        comp = (r.get("component") or "").strip()
        op_type = (r.get("op_type") or "").strip()
        counts[(comp, op_type)] += 1

    for key, expected_key in [
        (("vision", "linear"), "vision_linear"),
        (("vlm", "linear"), "vlm_linear"),
        (("expert", "linear"), "expert_linear"),
        (("vlm", "matmul"), "vlm_matmul"),
        (("expert", "matmul"), "expert_matmul"),
    ]:
        if counts[key] != EXPECTED[expected_key]:
            errs.append(f"{key}={counts[key]} expected={EXPECTED[expected_key]}")

    if len(weight_rows) != EXPECTED["static_weight_rows"]:
        errs.append(
            f"weight rows={len(weight_rows)} expected={EXPECTED['static_weight_rows']}"
        )

    comps = {(r.get("component") or "").strip() for r in module_rows}
    if not {"vision", "vlm", "expert"}.issubset(comps):
        errs.append(f"runtime components missing: got={sorted(comps)}")

    expert_steps = {
        str(r.get("flow_step", "")).strip()
        for r in module_rows
        if (r.get("component") or "").strip() == "expert"
    }
    missing_steps = {str(x) for x in range(10)} - expert_steps
    if missing_steps:
        errs.append(f"Expert denoise flow steps missing: {sorted(missing_steps)}")

    if n_gen <= 0:
        errs.append(f"invalid sample_actions generations={n_gen}")

    vision_linear = next(
        (r for r in compute_rows
         if r["component"] == "vision" and r["block"] == "Vision 72 Linear"),
        None,
    )
    if vision_linear:
        got = float(vision_linear["GFLOPs_per_sample_actions"])
        # V0 audited reference is 347.89 GFLOPs for the 72 Linear ops.
        if abs(got - 347.89) / 347.89 > 0.02:
            errs.append(
                f"Vision Linear compute={got:.3f} GFLOPs, expected ~347.89 "
                "(>2% mismatch)"
            )
    else:
        errs.append("Vision Linear compute row missing")

    return errs, counts


def write_csv(path: Path, rows):
    path.parent.mkdir(parents=True, exist_ok=True)
    if not rows:
        raise RuntimeError(f"refusing to write empty CSV: {path}")
    fields = list(rows[0].keys())
    with path.open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        w.writerows(rows)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--output", default=str(DEFAULT_OUT))
    args = ap.parse_args()
    out = Path(args.output).resolve()
    sp = out / "sparsity"

    module_rows = read_csv(sp / "module_sparsity.csv")
    weight_rows = read_csv(sp / "weight_sparsity_static.csv")
    manifest_rows = read_csv(sp / "quantization_manifest.csv")
    workload_rows = read_csv(sp / "workload.csv")

    summary, operator_rows = aggregate_sparsity(module_rows, weight_rows)
    n_gen, compute_rows, quant_coverage = aggregate_compute(workload_rows)
    errs, counts = check_manifest(
        manifest_rows, weight_rows, module_rows, compute_rows, n_gen
    )

    write_csv(out / "sparsity_compute_summary.csv", summary)
    write_csv(out / "sparsity_by_operator.csv", operator_rows)
    write_csv(out / "compute_summary.csv", compute_rows)

    print("=" * 88)
    print("VLIN VISION SPARSITY + COMPUTE SUMMARY")
    print("=" * 88)
    print(f"output                  : {out}")
    print(f"sample_actions inferred : {n_gen}")
    print(f"manifest rows           : {len(manifest_rows)}")
    print(f"static weight rows      : {len(weight_rows)}")
    print(
        "routing                 : "
        f"vision Linear={counts[('vision','linear')]}, "
        f"vlm Linear/MatMul={counts[('vlm','linear')]}/"
        f"{counts[('vlm','matmul')]}, "
        f"expert Linear/MatMul={counts[('expert','linear')]}/"
        f"{counts[('expert','matmul')]}"
    )
    print()
    print("Primary sparsity (native runtime counters):")
    for r in summary:
        print(
            f"  {r['component']:13s} "
            f"runtime elem={100*float(r['runtime_element_sparsity_native']):6.2f}% "
            f"bit={100*float(r['runtime_bit_sparsity_native']):6.2f}% | "
            f"weight elem={100*float(r['weight_element_sparsity']):6.2f}% "
            f"bit={100*float(r['weight_bit_sparsity']):6.2f}%"
        )
    print()
    print("Compute per sample_actions():")
    for r in compute_rows:
        if r["component"] == "TOTAL":
            continue
        print(
            f"  {r['component']:9s} {r['block']:34s} "
            f"{float(r['GFLOPs_per_sample_actions']):9.3f} GFLOPs "
            f"quantized={r['quantized']}"
        )
    total = compute_rows[-1]
    print(
        f"  {'TOTAL':9s} {'audited major ops':34s} "
        f"{float(total['GFLOPs_per_sample_actions']):9.3f} GFLOPs"
    )
    print(f"  quantized major-op FLOP coverage: {100*quant_coverage:.2f}%")
    print()
    print("Metric caveat: FP8 bit sparsity is the framework's E4M3 significand")
    print("zero-bit metric, not the fraction of zero bits across the full 8-bit code.")
    print("Compute caveat: FLOPs/MACs are not measured latency or speedup.")

    if errs:
        print()
        print("GATE: FAIL")
        for e in errs:
            print(f"  - {e}")
        return 2

    print()
    print("GATE: PASS")
    print("Vision/VLM/Expert sparsity coverage and compute accounting are complete.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
